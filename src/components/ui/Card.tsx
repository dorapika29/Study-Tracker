'use client';

import { HTMLAttributes, forwardRef } from 'react';
import { clsx } from 'clsx';

interface CardProps extends HTMLAttributes<HTMLDivElement> {
  variant?: 'default' | 'hover' | 'bordered';
  padding?: 'none' | 'sm' | 'md' | 'lg';
}

export const Card = forwardRef<HTMLDivElement, CardProps>(
  ({ className, variant = 'default', padding = 'md', children, ...props }, ref) => {
    const variantClasses = {
      default: 'bg-[rgb(var(--card))] text-[rgb(var(--card-foreground))] rounded-2xl border border-[rgb(var(--border))] shadow-sm transition-all duration-300',
      hover: 'bg-[rgb(var(--card))] text-[rgb(var(--card-foreground))] rounded-2xl border border-[rgb(var(--border))] shadow-sm transition-all duration-300 hover:shadow-lg hover:-translate-y-1',
      bordered: 'bg-[rgb(var(--card))] text-[rgb(var(--card-foreground))] rounded-2xl border-2 border-[rgb(var(--border))]',
    };

    const paddingClasses = {
      none: '',
      sm: 'p-3',
      md: 'p-4 sm:p-6',
      lg: 'p-6 sm:p-8',
    };

    return (
      <div
        ref={ref}
        className={clsx(variantClasses[variant], paddingClasses[padding], className)}
        {...props}
      >
        {children}
      </div>
    );
  }
);

Card.displayName = 'Card';

